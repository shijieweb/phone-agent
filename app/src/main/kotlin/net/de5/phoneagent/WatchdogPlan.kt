package net.de5.phoneagent

/**
 * 守护进程（watchdog）的纯逻辑：脚本内容、命令拼装、状态判定。
 *
 * 为什么要有它：Flyme 不投 MY_PACKAGE_REPLACED（v0.4.3 就证实了），静默安装
 * （`pm install`）装完 App 不会自己起来，老板必须手动点一次「启动」。实测发现
 * adbd 下用 setsid 起的进程能活过 App 被杀，所以让一个 uid 2000 的脚本每 60 秒
 * 看一次服务还在不在，不在就 `am start` 把界面拉起来——界面一起来
 * [StartPolicy.shouldStartOnOpen] 就会把服务带起来。
 *
 * 三条纪律，全部体现在这里：
 * 1. 防重复：起之前先 pgrep，同名脚本已在跑就不起第二个。
 * 2. 能停：停止时先写停止标记再 pkill，标记是第二道保险（pkill 漏了，脚本
 *    下一轮自己退出）。
 * 3. 不撒谎：自连 ADB 没连上时只说「未启用」，绝不假装守护在跑。
 *
 * 不 import 任何 android.*：脚本与判定必须能在 JVM 单测里跑。
 */
internal object WatchdogPlan {

    const val PACKAGE = "net.de5.phoneagent"
    const val SCRIPT_PATH = "/data/local/tmp/phoneagent-guard.sh"
    const val LOG_PATH = "/data/local/tmp/phoneagent-guard.log"

    /**
     * 停止标记：文件存在时脚本自杀。
     *
     * 为什么需要两道保险：pkill 靠匹配命令行，匹配串写错或进程正卡在 `am start`
     * 里都可能漏杀；标记是幂等的，漏杀也只是一轮之后退出。
     */
    const val OFF_MARKER = "/data/local/tmp/phoneagent-guard.off"

    /** pgrep -f 的匹配串，必须与脚本文件名一致（否则防重复判断失效）。 */
    const val MARK = "phoneagent-guard.sh"

    /** dumpsys 输出里用来判断服务是否还在的类名。 */
    const val SERVICE_CLASS = "RcAgentService"

    /** 检查间隔：60 秒。太短会一直唤醒 CPU，太长老板会觉得「装完没反应」。 */
    const val INTERVAL_SECONDS = 60

    /**
     * 守护日志的硬上限：64KB（v0.5.8-pad12）。
     *
     * 过去这个文件是**唯一**无界的东西：每重启一次追加一行，谁也不会来删。
     * 现在脚本每轮追加前先自检大小，超了就先裁到末 [LOG_KEEP_LINES] 行再写；
     * arm 的时候也先裁一次，免得上一版留下的巨无霸继续长。
     */
    const val LOG_MAX_BYTES = 64 * 1024

    /** 裁的时候保留末尾这么多行：够看最近几十次重启，又不至于一眼看不到头。 */
    const val LOG_KEEP_LINES = 200

    /** 脚本里把 wc 的补位空格去掉；只用双引号，脚本里一个单引号都不许有。 */
    private const val TRIM_SPACE = "\" \""

    const val USAGE = "usage: watchdog [status] | watchdog arm | watchdog disarm"

    /** 脚本里必须用到的美元符；直接写 $ 会被 Kotlin 当模板插值，用 Char 拼。 */
    const val D = '$'

    /**
     * 脚本版本标记（v0.6.3-pad12）。
     *
     * 存在的理由是一个真机坑：arm 先探进程，发现已经在跑就直接回「已在运行」，
     * 于是**旧脚本永远不会被换掉**。真机上就见过 /data/local/tmp/phoneagent-guard.sh
     * 还是 v0.5.8 那版（头部没有 CAP= 那行），日志永远封不了顶，而 App 一直说
     * 「守护已在运行」。
     *
     * 规则：**改了 [script] 就改这里**。arm 先比这个标记，对不上就强杀旧进程、
     * 重写脚本、再起一次。
     */
    const val SCRIPT_VERSION = "v0.6.3-pad12"

    /** 脚本第二行；[stampCommand] 就是拿它去数命中行数。 */
    const val SCRIPT_STAMP_LINE = "# ver=" + SCRIPT_VERSION

    /**
     * 守护脚本全文。
     *
     * 三条约束写在脚本里：
     * - 只查 dumpsys，不查包是否被 force-stop：force-stop 之后我们要的正是重启。
     * - 每轮都查停止标记，所以 disarm 与脚本退出之间没有竞态窗口。
     * - 单引号一个都不许出现：写脚本走的是 `echo '行'`，行内有单引号就截断了。
     */
    fun script(): String = listOf(
        "#!/system/bin/sh",
        SCRIPT_STAMP_LINE,
        "# phone-agent guard. Generated by the app, never downloaded.",
        "# One job: if RcAgentService is gone, pull the UI up so the service returns.",
        "LOG=" + LOG_PATH,
        "PKG=" + PACKAGE,
        "CAP=" + LOG_MAX_BYTES,
        "if [ -f " + OFF_MARKER + " ]; then exit 0; fi",
        "while true; do",
        "  if [ -f " + OFF_MARKER + " ]; then exit 0; fi",
        "  if ! dumpsys activity services " + D + "PKG 2>/dev/null | grep -q " + SERVICE_CLASS + "; then",
        "    SZ=" + D + "(wc -c < " + D + "LOG 2>/dev/null | tr -d " + TRIM_SPACE + ")",
        "    if [ " + D + "{SZ:-0} -gt " + D + "CAP ]; then tail -n " + LOG_KEEP_LINES +
            " " + D + "LOG > " + D + "LOG.tmp && mv " + D + "LOG.tmp " + D + "LOG; fi",
        "    echo " + D + "(date +%Y-%m-%dT%H:%M:%S) restart >> " + D + "LOG",
        "    am start -n " + D + "PKG/.MainActivity >/dev/null 2>&1",
        "  fi",
        "  sleep " + INTERVAL_SECONDS,
        "done"
    ).joinToString("\n") + "\n"

    /**
     * 把脚本落到 /data/local/tmp 的命令（单行）。
     *
     * 用 `: > 文件` 加一串 `echo '行' >> 文件`，而不是 printf/heredoc：
     * 命令要整条塞进 PTY 的一行，任何换行都会被交互式 shell 逐行执行掉。
     */
    fun writeCommand(): String {
        val sb = StringBuilder(": > " + SCRIPT_PATH)
        for (line in script().trimEnd('\n').split("\n")) {
            sb.append("; echo '").append(line).append("' >> ").append(SCRIPT_PATH)
        }
        sb.append("; chmod 755 ").append(SCRIPT_PATH)
        return sb.toString()
    }

    /**
     * 启动守护的命令。
     *
     * setsid 是关键：它把脚本放进独立会话，App 的进程死掉不会连带杀掉它
     * （真机实测：force-stop 之后 setsid 起的进程照样跑完）。
     * 先删停止标记，否则上一轮 disarm 留下的标记会让脚本立刻退出。
     */
    fun armCommand(): String =
        "rm -f " + OFF_MARKER +
            "; if [ -f " + LOG_PATH + " ]; then SZ=" + D + "(wc -c < " + LOG_PATH +
            " 2>/dev/null | tr -d " + TRIM_SPACE + "); if [ " + D + "{SZ:-0} -gt " +
            LOG_MAX_BYTES + " ]; then tail -n " + LOG_KEEP_LINES + " " + LOG_PATH +
            " > " + LOG_PATH + ".tmp && mv " + LOG_PATH + ".tmp " + LOG_PATH +
            "; fi; fi" +
            "; setsid sh " + SCRIPT_PATH + " >/dev/null 2>&1 &"

    /**
     * 停止守护的命令：先写标记（幂等），再**强杀三遍**，最后回读一次进程表。
     *
     * v0.6.3-pad12 修的真机坑：原来只 `pkill -f`（SIGTERM）加 `sleep 1`，结果
     * 报「还有进程 3004」，而手动 `kill 3004` 却回 "No such process"。原因是脚本
     * 主体是 `while true; do ...; sleep 60; done`：POSIX 规定 shell 在 wait 子进程
     * 时不响应 SIGTERM，得等那 60 秒的 sleep 结束才会退出，1 秒后自然还看得见。
     *
     * 所以：`pkill -9`（SIGKILL 不可阻塞，内核直接收尸）＋ 0.5 秒间隔重试三次，
     * 三次都杀不掉才把进程号报出去。
     *
     * pkill 的匹配串与脚本名一致；pkill 不会杀自己，PTY 的 shell 命令行是 `sh`，
     * 也不在匹配范围内。命令串里不放单引号，跟 [writeCommand] 保持同一习惯。
     */
    fun disarmCommand(): String {
        val kill = "; pkill -9 -f " + MARK + "; sleep 0.5"
        return "echo off > " + OFF_MARKER + kill + kill + kill +
            "; pgrep -f " + MARK + " || echo"
    }

    /**
     * 读脚本头部的版本标记命中行数：1 = 当前版本，0 = 旧脚本或还没写。
     *
     * 为什么用 `grep -c` 而不是 `grep -q`：要一个**能解析的答案**，而 `-q` 只给
     * 退出码；PTY 回显里命令行本身也含这个标记，靠退出码分不清是回显还是真命中。
     * 计数行是纯数字，跟回显行混不了（见 [parseScriptCurrent]）。
     */
    fun stampCommand(): String =
        "grep -c ver=" + SCRIPT_VERSION + " " + SCRIPT_PATH + " 2>/dev/null || echo 0"

    /**
     * [stampCommand] 的解析：只看**整行都是数字**的那些行，取最后一个。
     *
     * PTY 会把命令行回显出来，那行里有字母也有这个标记，不是纯数字，所以骗不到。
     */
    fun parseScriptCurrent(raw: String): Boolean =
        raw.lineSequence()
            .map { it.trim() }
            .filter { it.isNotEmpty() && it.all { ch -> ch.isDigit() } }
            .lastOrNull()
            ?.toIntOrNull()
            ?.let { it > 0 } ?: false

    /** 只查进程表；`|| echo` 保证 pgrep 没命中时退出码仍是 0，不让哨兵误报。 */
    fun probeCommand(): String = "pgrep -f " + MARK + " || echo"

    /**
     * 状态查询：一次 shell 往返拿三样东西（进程、日志末行、停止标记）。
     *
     * 用 PIDS/LOG/OFF 三个锚点分段，[parseStatus] 按锚点解析——比固定行号稳，
     * 因为 tail 或 pgrep 少输出一行时行号会整体错位。
     */
    fun statusCommand(): String =
        "echo PIDS; pgrep -f " + MARK + " || echo; echo LOG; tail -n 1 " + LOG_PATH +
            " 2>/dev/null || echo; echo OFF; [ -f " + OFF_MARKER + " ] && echo 1 || echo 0"

    /** 从任意文本里抽出进程号（pgrep 每行一个，也可能带别的噪声）。 */
    fun parsePids(raw: String): List<Int> =
        Regex("[0-9]+").findAll(raw).mapNotNull { it.value.toIntOrNull() }.filter { it > 0 }.toList()

    /** [statusCommand] 的解析结果。 */
    data class Status(val pids: List<Int>, val lastRestart: String?, val offMarker: Boolean)

    fun parseStatus(raw: String): Status {
        var pids = emptyList<Int>()
        var lastRestart: String? = null
        var off = false
        var mode = ""
        val lines = raw.replace("\r\n", "\n").replace('\r', '\n').split("\n").map { it.trim() }
        for (line in lines) {
            when {
                line == "PIDS" -> mode = "pids"
                line == "LOG" -> mode = "log"
                line == "OFF" -> mode = "off"
                mode == "pids" && line.isNotEmpty() -> pids = pids + parsePids(line)
                mode == "log" && line.isNotEmpty() -> lastRestart = line
                // 空行必须跳过：命令输出末尾的换行会多出一个空行，
                // 直接赋值会把已经看到的 "1" 又抹回 false。
                mode == "off" && line.isNotEmpty() -> off = line == "1"
            }
        }
        return Status(pids, lastRestart, off)
    }

    /**
     * 该不该起守护。
     *
     * 服务本身必须在跑（否则守护一起来就会去拉界面，等于绕过老板按下的「停止」）。
     * 另外两个条件满足**任一**即可动手：同名脚本还没在跑（正常 arm），或者脚本
     * 版本对不上（v0.6.3-pad12 加的，否则旧脚本永远换不掉，见 [SCRIPT_VERSION]）。
     */
    fun shouldArm(existingPids: List<Int>, scriptCurrent: Boolean, serviceRunning: Boolean): Boolean =
        serviceRunning && (existingPids.isEmpty() || !scriptCurrent)

    /**
     * 该不该停守护。
     *
     * 判据是 autoStart 而不是「服务是否在跑」：老板点停止时 [StartPolicy.onToggle]
     * 已经把 autoStart 清成 false，而服务自己重启（START_STICKY）时 autoStart 仍是
     * true —— 那种情况绝不能把守护停掉，否则一次系统回收就永久失去自愈。
     */
    fun shouldDisarm(autoStart: Boolean): Boolean = !autoStart

    fun status(
        adbConnected: Boolean,
        pids: List<Int>,
        lastRestart: String?,
        offMarker: Boolean
    ): String {
        val sb = StringBuilder()
        when {
            !adbConnected -> sb.append("守护: 未知（自连 ADB 未连接）")
            pids.isNotEmpty() -> sb.append("守护: 运行中（pid ").append(pids.joinToString(",")).append("）")
            else -> sb.append("守护: 未运行")
        }
        sb.append('\n')
        sb.append("最近重启: ").append(if (lastRestart.isNullOrBlank()) "(无记录)" else lastRestart)
        sb.append('\n')
        sb.append("自连 ADB: ").append(if (adbConnected) "已连接" else "未连接").append('\n')
        sb.append("停止标记: ").append(if (offMarker) "存在（已 disarm）" else "不存在").append('\n')
        sb.append("脚本: ").append(SCRIPT_PATH).append('\n')
        sb.append("间隔: ").append(INTERVAL_SECONDS).append("s").append('\n')
        sb.append("命令: ").append(USAGE.removePrefix("usage: "))
        return sb.toString()
    }

    /** 自动 arm 时的静默降级：只记一行日志，不当错误喊出来。 */
    fun adbUnavailable(): String = "守护未启用：自连 ADB 未连接"

    /**
     * 手动 arm / disarm 时的拒绝文案。
     *
     * 必须带 [Admin.ERROR_PREFIX]：Executor 只靠这个前缀把失败翻成 exit 6，
     * 少了它「自连 ADB 没连上」会被当成成功回 exit 0，控制器就会以为守护已开。
     */
    fun armUnavailable(): String = Admin.ERROR_PREFIX + "守护启用失败: 自连 ADB 未连接（先执行 shconnect）"

    fun disarmUnavailable(): String = Admin.ERROR_PREFIX + "守护停止失败: 自连 ADB 未连接（先执行 shconnect）"

    fun armOk(pids: List<Int>): String =
        "已启用守护（pid " + pids.joinToString(",") + "，每 " + INTERVAL_SECONDS + "s 检查一次）"

    /** 旧脚本被杀掉换新版之后说的话；不说清楚操作员会以为什么都没发生。 */
    fun armReplaced(pids: List<Int>): String =
        "已换掉旧脚本并启用守护（pid " + pids.joinToString(",") + "，版本 " + SCRIPT_VERSION +
            "，每 " + INTERVAL_SECONDS + "s 检查一次）"

    /** 旧脚本杀不掉时的拒绝文案：宁可不 arm，也不让两个脚本同时跑。 */
    fun armStuck(pids: List<Int>): String =
        Admin.ERROR_PREFIX + "守护启用失败: 旧脚本杀不掉（pid " + pids.joinToString(",") +
            "），先手动 kill -9 再试"

    fun armAlready(pids: List<Int>): String =
        "守护已在运行（pid " + pids.joinToString(",") + "），未重复启动"

    fun armNeedsService(): String = Admin.ERROR_PREFIX + "守护启用失败: 服务未运行（先启动 agent）"

    fun armFailed(why: String): String = Admin.ERROR_PREFIX + "守护启用失败: " + why

    fun disarmOk(): String = "已停止守护（写了停止标记并结束进程）"

    fun disarmFailed(why: String): String = Admin.ERROR_PREFIX + "守护停止失败: " + why
}